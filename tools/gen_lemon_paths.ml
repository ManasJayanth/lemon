(* Generate lemon_paths.ml from environment variables.

   Baked development paths (from the esy sandbox) take precedence when they
   exist; installed packages resolve everything relative to the executable
   (<exe_dir>/../lib/lemon), with LEMON_LIB as an override. The executable
   directory resolves through symlinks so Homebrew/winget symlinked installs
   find their library tree.

   Reads MELANGESTDLIB_VALUE, MELANGEASSETS_VALUE, REACTLIB_VALUE,
   NPMREACT_VALUE from the environment; writes lemon_paths.ml to cwd. *)

let escape s =
  let buf = Buffer.create (String.length s + 8) in
  String.iter (fun c ->
      match c with
      | '"' -> Buffer.add_string buf "\\\""
      | '\\' -> Buffer.add_string buf "\\\\"
      | '\n' -> Buffer.add_string buf "\\n"
      | c -> Buffer.add_char buf c) s;
  Buffer.contents buf

let getenv_or_fail name =
  match Sys.getenv_opt name with
  | Some v -> v
  | None -> prerr_endline ("gen_lemon_paths: missing env " ^ name); exit 1

