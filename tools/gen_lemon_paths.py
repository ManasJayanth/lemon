#!/usr/bin/env python3
"""Generate lemon_paths.ml.

Baked development paths (from the esy sandbox) take precedence when they
exist; installed packages resolve everything relative to the executable
(`<exe_dir>/../lib/lemon`), with LEMON_LIB as an override. The executable
directory resolves through symlinks so Homebrew/winget symlinked installs
find their library tree.
"""
import json
import os

stdlib = os.environ["MELANGESTDLIB_VALUE"]
assets = os.environ["MELANGEASSETS_VALUE"]
reactlib = os.environ["REACTLIB_VALUE"]
npmreact = os.environ["NPMREACT_VALUE"]

with open("lemon_paths.ml", "w") as fh:
    fh.write("""\
(* Generated by build.sh via tools/gen_lemon_paths.py. *)
let absolute p =
  if Filename.is_relative p then Filename.concat (Sys.getcwd ()) p else p

(* Resolve through symlinks: Homebrew and winget expose bin/lemon as a
   symlink into the real Cellar/package directory. *)
let exe_dir () =
  (* argv(0) may be a bare command name found through PATH *)
  let resolve_on_path name =
    match (try Some (Sys.getenv "PATH") with Not_found -> None) with
    | None -> None
    | Some paths ->
      let rec go = function
        | [] -> None
        | dir :: rest ->
          let cand = Filename.concat dir name in
          if Sys.file_exists cand then Some cand else go rest
      in
      let dirs = String.split_on_char ':' paths in
        go (List.filter (fun d -> d <> "") dirs)
  in
  let argv0 =
    if String.contains Sys.argv.(0) Filename.dir_sep.[0] || Sys.file_exists Sys.argv.(0)
    then absolute Sys.argv.(0)
    else match resolve_on_path Sys.argv.(0) with
      | Some p -> p
      | None -> absolute Sys.argv.(0)
  in
  let real =
    try let st = Unix.stat argv0 in ignore st.Unix.st_kind; argv0
    with _ -> argv0
  in
  Filename.dirname real

let installed_root () =
  match (try Some (Sys.getenv "LEMON_LIB") with Not_found -> None) with
  | Some d -> absolute d
  | None -> Filename.concat (exe_dir ()) "../lib/lemon"

let pick baked rel =
  if Sys.file_exists baked then baked
  else Filename.concat (installed_root ()) rel

let plugin name =
  let beside = Filename.concat (exe_dir ()) name in
  if Sys.file_exists beside then beside
  else Filename.concat (installed_root ()) name

""")
    fh.write('let melange_stdlib = pick %s "melange-stdlib"\n' % json.dumps(stdlib))
    fh.write('let melange_assets = pick %s "melange-assets"\n' % json.dumps(assets))
    fh.write('let react_lib = pick %s "react-lib"\n' % json.dumps(reactlib))
    fh.write('let melange_js_lib = pick %s "melange-js"\n'
             % json.dumps(os.path.normpath(os.path.join(stdlib, "..", "js", "melange"))))
    fh.write('let react_npm = pick %s "react-npm"\n' % json.dumps(npmreact))
