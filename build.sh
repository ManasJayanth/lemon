#!/bin/sh
# Build Lemon: the coordinator executable plus the compiler worker plugin.
# The plugin bundles the stock OCaml compiler libraries and the pinned Reason
# parser into one dynlinkable archive; everything runs inside worker domains,
# so compilation never spawns compiler processes (bytecode path).
set -eu
cd "$(dirname "$0")"

OCAMLLIB=$(ocamlc -where)
OCAMLC=$(command -v ocamlc)
OCAMLRUN=$(command -v ocamlrun)
OCAMLOBJINFO=$(command -v ocamlobjinfo)

# Locate a findlib-style package directory on OCAMLPATH.
pkgdir() {
  name=$1
  saved=$IFS
  IFS=:
  for d in $OCAMLPATH; do
    if [ -e "$d/$name" ]; then
      IFS=$saved
      printf '%s\n' "$d/$name"
      return 0
    fi
  done
  IFS=$saved
  echo "build.sh: cannot locate package '$name' on OCAMLPATH" >&2
  exit 1
}

PPXLIB=$(pkgdir ppxlib)
MENHIR=$(pkgdir menhirLib)
REASON=$(pkgdir reason)
SHADOW=$(pkgdir ocaml-compiler-libs)/shadow
SEXPLIB0=$(pkgdir sexplib0)
PPXDERIVERS=$(pkgdir ppx_derivers)

WORKER_INCLUDES="-I $OCAMLLIB/compiler-libs -I $REASON -I $REASON/easy_format \
 -I $REASON/ocaml-migrate-parsetree -I $PPXLIB -I $PPXLIB/ast -I $PPXLIB/astlib \
 -I $PPXLIB/stdppx -I $PPXLIB/print_diff -I $PPXLIB/traverse_builtins \
 -I $MENHIR -I $SHADOW -I $SEXPLIB0 -I $PPXDERIVERS"

# --- worker API + worker implementation (links the pinned Reason) ---------
"$OCAMLC" -c worker_api.ml
"$OCAMLC" $WORKER_INCLUDES -c compiler_worker.ml

# --- the worker plugin: one archive, valid link order ---------------------
ARCHIVES="
$OCAMLLIB/compiler-libs/ocamlcommon.cma
$OCAMLLIB/compiler-libs/ocamlbytecomp.cma
$SHADOW/ocaml_shadow.cma
$SEXPLIB0/sexplib0.cma
$PPXDERIVERS/ppx_derivers.cma
$PPXLIB/astlib/astlib.cma
$PPXLIB/ast/ppxlib_ast.cma
$PPXLIB/print_diff/ppxlib_print_diff.cma
$PPXLIB/stdppx/stdppx.cma
$PPXLIB/traverse_builtins/ppxlib_traverse_builtins.cma
$PPXLIB/ppxlib.cma
$MENHIR/menhirLib.cma
$REASON/easy_format/reason_easy_format.cma
$REASON/ocaml-migrate-parsetree/reason_omp.cma
$REASON/reason.cma
compiler_worker.cmo
"
# shellcheck disable=SC2086
ORDER=$(python3 tools/bundle_order.py $ARCHIVES)
# shellcheck disable=SC2086
"$OCAMLC" -nostdlib -a -linkall $ORDER -o compiler_worker.cma

# --- force every stdlib unit into the main executable ---------------------
# Dynlinked plugins may reference any stdlib unit; the implicit stdlib link
# only includes units the coordinator itself uses.
"$OCAMLOBJINFO" "$OCAMLLIB/stdlib.cma" | grep '^Unit name:' | awk '{print $3}' \
  | grep -v '^Stdlib$' > .stdlib-units.txt
{
  echo '(* Generated by build.sh: keep every stdlib unit in the link. *)'
  i=0
  while read -r unit; do
    mod=$(printf '%s' "$unit" | sed 's/__/./g')
    echo "module type ForceT$i = module type of $mod"
    echo "let _force_$i = (module $mod : ForceT$i)"
    i=$((i + 1))
  done < .stdlib-units.txt
} > force_stdlib.ml
"$OCAMLC" -c force_stdlib.ml
rm -f .stdlib-units.txt

# --- the coordinator -------------------------------------------------------
"$OCAMLC" -I +unix -I +dynlink -linkall unix.cma dynlink.cma \
  worker_api.cmo force_stdlib.cmo lemon.ml -o lemon.byte

echo "build.sh: lemon.byte + compiler_worker.cma ready"
