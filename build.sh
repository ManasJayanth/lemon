#!/bin/sh
# Build Lemon: the coordinator executable plus the compiler worker plugin.
# The plugin bundles the stock OCaml compiler libraries and the pinned Reason
# parser into one dynlinkable archive; everything runs inside worker domains,
# so compilation never spawns compiler processes (bytecode path).
set -eu
cd "$(dirname "$0")"

OCAMLC=$(command -v ocamlc)

# Build-time helpers are compiled OCaml: the toolchain inside the esy
# sandbox provides the compiler, so no external interpreter is needed.
# Use +unix (ocamlc's built-in stdlib-relative path) so the commands work
# regardless of how the sandbox maps the installation directory.
"$OCAMLC" -I +unix -o tools/bundle_order \
  unix.cma tools/bundle_order.ml
"$OCAMLC" -I +unix -o tools/js_bundle_order \
  unix.cma tools/js_bundle_order.ml
"$OCAMLC" -I +unix -o tools/gen_lemon_paths \
  unix.cma tools/gen_lemon_paths.ml
OCAMLRUN=$(command -v ocamlrun)
OCAMLOBJINFO=$(command -v ocamlobjinfo)

# Locate a findlib-style package directory on OCAMLPATH.
pkgdir() {
  name=$1
  saved=$IFS
  IFS=:
  for d in $OCAMLPATH; do
    if [ -e "$d/$name" ]; then
      IFS=$saved
      printf '%s\n' "$d/$name"
      return 0
    fi
  done
  IFS=$saved
  echo "build.sh: cannot locate package '$name' on OCAMLPATH" >&2
  exit 1
}

PPXLIB=$(pkgdir ppxlib)
MENHIR=$(pkgdir menhirLib)
REASONREACT=${reason_react_lemon__lib:-$(pkgdir reason-react)}/reason-react
REASON=${reason_lemon__lib:-$(pkgdir reason)}/reason
SHADOW=$(pkgdir ocaml-compiler-libs)/shadow
SEXPLIB0=$(pkgdir sexplib0)
PPXDERIVERS=$(pkgdir ppx_derivers)
DBI=$(pkgdir dune-build-info)

WORKER_INCLUDES="-I $OCAMLLIB/compiler-libs -I $REASON -I $REASON/easy_format \
 -I $REASON/ocaml-migrate-parsetree -I $PPXLIB -I $PPXLIB/ast -I $PPXLIB/astlib \
 -I $PPXLIB/stdppx -I $PPXLIB/print_diff -I $PPXLIB/traverse_builtins \
 -I $MENHIR -I $SHADOW -I $SEXPLIB0 -I $PPXDERIVERS"

# --- worker API + worker implementation (links the pinned Reason) ---------
"$OCAMLC" -c worker_api.ml
"$OCAMLC" $WORKER_INCLUDES -c compiler_worker.ml

# --- the worker plugin: one archive, valid link order ---------------------
ARCHIVES="
$OCAMLLIB/compiler-libs/ocamlcommon.cma
$OCAMLLIB/compiler-libs/ocamlbytecomp.cma
$SHADOW/ocaml_shadow.cma
$SEXPLIB0/sexplib0.cma
$PPXDERIVERS/ppx_derivers.cma
$PPXLIB/astlib/astlib.cma
$PPXLIB/ast/ppxlib_ast.cma
$PPXLIB/print_diff/ppxlib_print_diff.cma
$PPXLIB/stdppx/stdppx.cma
$PPXLIB/traverse_builtins/ppxlib_traverse_builtins.cma
$PPXLIB/ppxlib.cma
$MENHIR/menhirLib.cma
$REASON/easy_format/reason_easy_format.cma
$REASON/ocaml-migrate-parsetree/reason_omp.cma
$REASON/reason.cma
compiler_worker.cmo
"
# shellcheck disable=SC2086
ORDER=$(tools/bundle_order $ARCHIVES)
# shellcheck disable=SC2086
"$OCAMLC" -nostdlib -a -linkall $ORDER -o compiler_worker.cma

# --- force every stdlib unit into the main executable ---------------------
# Dynlinked plugins may reference any stdlib unit; the implicit stdlib link
# only includes units the coordinator itself uses.
"$OCAMLOBJINFO" "$OCAMLLIB/stdlib.cma" | grep '^Unit name:' | awk '{print $3}' \
  | grep -v '^Stdlib$' > .stdlib-units.txt
{
  echo '(* Generated by build.sh: keep every stdlib unit in the link. *)'
  i=0
  while read -r unit; do
    mod=$(printf '%s' "$unit" | sed 's/__/./g')
    echo "module type ForceT$i = module type of $mod"
    echo "let _force_$i = (module $mod : ForceT$i)"
    i=$((i + 1))
  done < .stdlib-units.txt
} > force_stdlib.ml
"$OCAMLC" -c force_stdlib.ml
rm -f .stdlib-units.txt

# --- Melange embed: vendored jscomp/core at the pinned tag ----------------
MELANGE=$(pkgdir melange)
EMBED_OUT=$PWD/embed
export MELANGE_LIB=$MELANGE
LEMON_EMBED_OUT=$EMBED_OUT sh vendor/melange-embed/build-embed.sh

# --- the Melange worker plugin --------------------------------------------
RR=${reason_react_lemon__lib:-}
if [ -n "$RR" ]; then
  RRPX=$RR/reason-react-ppx
  RRLIB=$RR/reason-react/melange
else
  RRPX=$(pkgdir reason-react-ppx)
  RRLIB=$(pkgdir reason-react)/melange
fi
MENHIRSDK=""
EMBED_INC="-I $EMBED_OUT/melangelib -I $MELANGE/__private__/melange_compiler_libs/.public_cmi \
 -I $MELANGE/__private__/melstd/.public_cmi -I $MELANGE/__private__/melange_ffi/.public_cmi \
 -I $MELANGE/__private__/pp/.public_cmi -I $MELANGE/__private__/melange_wrapper/.public_cmi \
 -I $MELANGE/js_parser -I $RRPX -I $RRLIB"
"$OCAMLC" $WORKER_INCLUDES $EMBED_INC -c melange_worker.ml

JS_ARCHIVES="
$OCAMLLIB/compiler-libs/ocamlcommon.cma
$SHADOW/ocaml_shadow.cma
$SEXPLIB0/sexplib0.cma
$PPXDERIVERS/ppx_derivers.cma
$PPXLIB/astlib/astlib.cma
$PPXLIB/ast/ppxlib_ast.cma
$PPXLIB/print_diff/ppxlib_print_diff.cma
$PPXLIB/stdppx/stdppx.cma
$PPXLIB/traverse_builtins/ppxlib_traverse_builtins.cma
$PPXLIB/ppxlib.cma
$MENHIR/menhirLib.cma
$REASON/easy_format/reason_easy_format.cma
$REASON/ocaml-migrate-parsetree/reason_omp.cma
$REASON/reason.cma
$MELANGE/js_parser/js_parser.cma
$MELANGE/ppx/melange_ppx.cma
$MELANGE/__private__/pp/pp.cma
$MELANGE/__private__/melange_wrapper/melange_wrapper.cma
$MELANGE/__private__/melstd/melstd.cma
$MELANGE/__private__/melange_compiler_libs/melange_compiler_libs.cma
$MELANGE/__private__/melange_ffi/melange_ffi.cma
$DBI/build_info.cma
$EMBED_OUT/version/build_info__Build_info_data.cmo
$RRPX/reason_react_ppx.cma
$EMBED_OUT/melangelib/melangelib__*.cmo
melange_worker.cmo
"
JS_ORDER=$(tools/bundle_order $JS_ARCHIVES | tools/js_bundle_order)
# shellcheck disable=SC2086
"$OCAMLC" -nostdlib -a -linkall $JS_ORDER -o melange_worker.cma

# --- Melange runtime assets, generated once with the pinned compiler ------
# (build-time asset generation; Lemon's own builds never invoke melc)
MELANGESTDLIB=$MELANGE/melange
MELANGERUNTIME=$MELANGE/js/melange
rm -rf melange-assets
mkdir -p melange-assets/node_modules/melange melange-assets/node_modules/melange.js
# Emit the JS runtime with the pinned compiler, exactly as upstream
# produces it (the runtime-export dune alias): melange, melange.js and
# melange.belt node_modules packages. (Build-time asset generation; Lemon's
# own builds never invoke melc.)
ASSETS_DIR=$PWD/melange-assets
rm -rf melange-assets
mkdir -p melange-assets/node_modules
(
  cd vendor/melange-embed/melange
  dune build @npm
  for pkg in melange melange.js melange.belt; do
    cp -RL "_build/default/runtime-export/x/node_modules/$pkg" "$ASSETS_DIR/node_modules/$pkg"
  done
)

# --- baked runtime paths for the coordinator ------------------------------
MELANGESTDLIB_VALUE="$MELANGESTDLIB" MELANGEASSETS_VALUE="$PWD/melange-assets" \
REACTLIB_VALUE="$RRLIB" NPMREACT_VALUE="$PWD/vendor/react-npm/node_modules" \
tools/gen_lemon_paths
"$OCAMLC" -c lemon_paths.ml

# --- the coordinator -------------------------------------------------------
"$OCAMLC" -I +unix -I +dynlink -linkall unix.cma dynlink.cma \
  worker_api.cmo force_stdlib.cmo lemon_paths.cmo lemon.ml -o lemon.byte

echo "build.sh: lemon.byte + compiler_worker.cma + melange_worker.cma ready"
